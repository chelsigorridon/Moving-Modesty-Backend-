/* eslint-disable @typescript-eslint/no-explicit-any -- Isolated PostgreSQL/provider/auth test doubles; never connects to live services. */
import assert from "node:assert/strict";
import test from "node:test";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { PGlite } from "@electric-sql/pglite";

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
test("discounts persist, validate server-owned prices and keep submitted PayFast/order/email snapshots immutable", async () => {
  const postgres = new PGlite();
  const database = require("drizzle-orm/pglite").drizzle(postgres);
  const modules = new Map<string, any>();
  const env: Record<string, string> = { DISCOUNTS_ENABLED: "true", NODE_ENV: "test", RESEND_API_KEY: "TEST-NOT-REAL", ORDER_NOTIFICATION_EMAIL: "owner@example.test" };
  let admin: any = { email: "owner@example.test", role: "owner" };
  const sent: any[] = [];
  const configuration = { environment: "production", merchantId: "12345678", merchantKey: "TEST-key", passphrase: "TEST-only", storeUrl: "https://store.test.invalid",
    processUrl: "https://www.payfast.co.za/eng/process", validationUrl: "https://test.invalid/validate", enforceSourceIp: false };
  function load(file: string): any {
    const absolute = resolve(root, file);
    if (/lib[\\/]db(?:[\\/]index)?\.ts$/.test(absolute)) return { db: database, requireDatabase: () => database };
    if (/payfast[\\/]configuration\.ts$/.test(absolute)) return { requirePayFastConfiguration: () => configuration };
    if (/lib[\\/]auth\.ts$/.test(absolute)) return { getRequestAdmin: async () => admin };
    if (/lib[\\/]monitoring\.ts$/.test(absolute)) return { reportFailure: async () => ({ reference: "TEST-REF" }), resolveFailures: async () => {}, getOperationalIssues: async () => [] };
    if (modules.has(absolute)) return modules.get(absolute);
    const compiledModule = { exports: {} }; modules.set(absolute, compiledModule.exports);
    const code = ts.transpileModule(readFileSync(absolute, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
    const localRequire = (name: string) => {
      if (name === "server-only") return {};
      if (name === "resend") return { Resend: class { emails = { send: async (message: any) => { sent.push(message); return { data: { id: randomUUID() }, error: null }; } }; } };
      if (name.startsWith("@/")) return load(name.slice(2) + ".ts");
      if (name.startsWith(".")) return load(resolve(dirname(absolute), name) + (name === "./db" ? "/index.ts" : name.endsWith(".ts") ? "" : ".ts"));
      return require(name);
    };
    new Function("require", "module", "exports", "process", code)(localRequire, compiledModule, compiledModule.exports, { env });
    return compiledModule.exports;
  }
  const originalFetch = globalThis.fetch;
  globalThis.fetch = async () => new Response("VALID");
  try {
    const journal = JSON.parse(readFileSync(resolve(root, "drizzle/meta/_journal.json"), "utf8"));
    for (const migration of journal.entries) for (const sql of readFileSync(resolve(root, `drizzle/${migration.tag}.sql`), "utf8").split("--> statement-breakpoint")) if (sql.trim()) await postgres.exec(sql);
    const { saveDiscount, listDiscounts, checkoutPricing } = load("lib/discounts.ts");
    const { discountSaveSchema } = load("lib/discount-input.ts");
    const { checkoutOrderSchema } = load("lib/checkout-input.ts");
    const { upsertCheckoutOrder } = load("lib/checkout-order.ts");
    const { createPayFastCheckout, recordPayFastCheckoutFailure } = load("lib/integrations/payfast/checkout.ts");
    const api = load("app/api/admin/discounts/route.ts");
    const customer = { firstName: "TEST", lastName: "Customer", email: "test@example.test", phone: "0821234567" };
    const input = { checkoutToken: randomUUID(), stage: "complete", fulfilmentMethod: "delivery", customer,
      address: { line1: "10 Test Street", suburb: "Test Suburb", city: "Cape Town", province: "Western Cape", postalCode: "0081" }, items: [{ sku: "AMINA-LAV-OS", quantity: 1 }] };
    assert.deepEqual((await listDiscounts()).discounts, []);
    const normal = await upsertCheckoutOrder(checkoutOrderSchema.parse(input), database);
    assert.equal(normal.discountAmount, 0); assert.equal(normal.total, 519);
    const create = (changes: any = {}) => discountSaveSchema.parse({ expectedRevision: 0, code: "SAVE10", type: "percentage", value: 10, ...changes });
    let saved = await saveDiscount(create(), admin.email, database);
    assert.equal(saved.active, false); assert.equal(saved.revision, 1);
    await assert.rejects(checkoutPricing("save10", [{ sku: "AMINA-LAV-OS", lineTotal: 420 }], "delivery", database), /not currently available/);
    saved = await saveDiscount({ ...saved, expectedRevision: saved.revision, active: true }, admin.email, database);
    await assert.rejects(saveDiscount({ ...saved, expectedRevision: 1 }, admin.email, database), /another tab/);
    await assert.rejects(saveDiscount(create({ code: "save10" }), admin.email, database), /already exists/);
    const discounted = checkoutOrderSchema.parse({ ...input, checkoutToken: randomUUID(), discountCode: " save10 ", discountAmount: 9999, total: 1 });
    const order = await upsertCheckoutOrder(discounted, database);
    assert.equal(order.subtotal, 420); assert.equal(order.discountAmount, 42); assert.equal(order.deliveryFee, 99); assert.equal(order.total, 477);
    const collection = await upsertCheckoutOrder({ ...discounted, checkoutToken: randomUUID(), fulfilmentMethod: "collection", address: undefined }, database);
    assert.equal(collection.total, 378); assert.equal(collection.deliveryFee, 0);
    const freeDelivery = await checkoutPricing("SAVE10", [{ lineTotal: 1680 }], "delivery", database);
    assert.equal(freeDelivery.discountAmount, 168); assert.equal(freeDelivery.deliveryFee, 0); assert.equal(freeDelivery.total, 1512);
    const boundaryDiscount = await checkoutPricing("SAVE10", [{ lineTotal: 1200 }], "delivery", database);
    assert.equal(boundaryDiscount.deliveryFee, 0); assert.equal(boundaryDiscount.total, 1080, "qualification stays before discounts");
    const belowBoundary = await checkoutPricing("SAVE10", [{ lineTotal: 1199.99 }], "delivery", database);
    assert.equal(belowBoundary.deliveryFee, 99);
    const thresholdOrderInput = checkoutOrderSchema.parse({ ...input, checkoutToken: randomUUID(), items: [{ sku: "AMINA-LAV-OS", quantity: 3 }] });
    const thresholdOrder = await upsertCheckoutOrder(thresholdOrderInput, database);
    assert.equal(thresholdOrder.subtotal, 1260); assert.equal(thresholdOrder.deliveryFee, 0); assert.equal(thresholdOrder.total, 1260);
    const thresholdPayment = await createPayFastCheckout({ orderNumber: thresholdOrder.orderNumber, checkoutToken: thresholdOrderInput.checkoutToken }, "https://test.invalid/checkout");
    assert.equal(thresholdPayment.fields.amount, "1260.00", "Neon order pricing and signed PayFast amount use the new threshold");
    const request = { orderNumber: order.orderNumber, checkoutToken: discounted.checkoutToken };
    const first = await createPayFastCheckout(request, "https://test.invalid/api/payments/payfast/checkout");
    assert.equal(first.fields.amount, "477.00");
    await recordPayFastCheckoutFailure(request, "TEST later configuration failure");
    assert.equal((await postgres.query<any>("select provider_status,status from payments where merchant_payment_id=$1", [order.orderNumber])).rows[0].provider_status, "CHECKOUT_STARTED");
    saved = await saveDiscount({ ...saved, code: "NEW15", value: 15, active: false, expectedRevision: saved.revision }, admin.email, database);
    assert.equal((await upsertCheckoutOrder(discounted, database)).total, 477, "the original code survives on a submitted payment");
    assert.equal((await createPayFastCheckout(request, "https://test.invalid/checkout")).fields.amount, "477.00");
    await assert.rejects(upsertCheckoutOrder({ ...discounted, checkoutToken: randomUUID() }, database), /not currently available/);
    await assert.rejects(createPayFastCheckout({ orderNumber: collection.orderNumber, checkoutToken: (await postgres.query<any>("select checkout_token from orders where order_number=$1", [collection.orderNumber])).rows[0].checkout_token }, "https://test.invalid/checkout"), /not currently available/);
    saved = await saveDiscount({ ...saved, active: true, expectedRevision: saved.revision }, admin.email, database);
    await assert.rejects(upsertCheckoutOrder({ ...discounted, discountCode: "NEW15" }, database), /new checkout/);
    const newCheckout = await upsertCheckoutOrder({ ...discounted, checkoutToken: randomUUID(), discountCode: "NEW15" }, database);
    assert.equal(newCheckout.total, 456);
    const { POST: restore } = load("app/api/checkout/session/route.ts");
    const session = await (await restore(new Request("https://test.invalid/api/checkout/session", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(request) }))).json();
    assert.equal(session.session.discountSnapshot.code, "SAVE10"); assert.equal(Number(session.session.discountAmount), 42);
    const { processPayFastNotification } = load("lib/integrations/payfast/notification.ts");
    const { createPayFastNotificationSignature } = load("lib/integrations/payfast/signature.ts");
    const params = new URLSearchParams({ merchant_id: configuration.merchantId, m_payment_id: order.orderNumber, pf_payment_id: "TEST-DISCOUNT-PAYMENT", payment_status: "COMPLETE", amount_gross: "477.00" });
    params.append("signature", createPayFastNotificationSignature(params, configuration.passphrase));
    assert.equal((await processPayFastNotification(new Request("https://test.invalid/notify", { method: "POST" }), params.toString())).paymentStatus, "paid");
    await assert.rejects(upsertCheckoutOrder({ ...discounted, discountCode: "NEW15" }, database), /paid or closed/);
    const { sendPaidOrderEmails } = load("lib/email.ts");
    const [{ id }] = (await postgres.query<any>("select id from orders where order_number=$1", [order.orderNumber])).rows;
    await sendPaidOrderEmails(id); assert.equal(sent.length, 2);
    for (const message of sent) {
      assert.match(message.template.variables.SUBTOTAL, /SAVE10.*42/);
      assert.match(message.template.variables.ORDER_TOTAL, /477/);
      assert.equal("DISCOUNT_CODE" in message.template.variables, false, "reuse the published template variables");
    }
    const row = (await load("lib/admin-data.ts").getAdminSnapshot()).orders.find((entry: any) => entry.id === order.orderNumber);
    assert.equal(row.discountCode, "SAVE10"); assert.equal(row.discountAmount, 42); assert.equal(row.total, 477);
    const productId = randomUUID();
    await postgres.query("insert into products (id,name,slug,category,status) values ($1,'Amina','test-amina','Scarves','active')", [productId]);
    await postgres.query("insert into product_variants (product_id,sku,colour,size,price) values ($1,'AMINA-LAV-OS','Lavender','One size',420)", [productId]);
    await saveDiscount(create({ code: "AMINAONLY", type: "amount", value: 500, active: true, productIds: [productId] }), admin.email, database);
    const scoped = await checkoutPricing("AMINAONLY", [{ sku: "AMINA-LAV-OS", lineTotal: 420 }, { sku: "HAWA-BLK-S", lineTotal: 450 }], "delivery", database);
    assert.equal(scoped.discountAmount, 420); assert.equal(scoped.total, 549);
    await assert.rejects(checkoutPricing("AMINAONLY", [{ sku: "HAWA-BLK-S", lineTotal: 450 }], "collection", database), /does not apply/);
    await saveDiscount(create({ code: "EXPIRED", active: true, endsAt: "2000-01-01T00:00:00Z" }), admin.email, database);
    await assert.rejects(checkoutPricing("EXPIRED", [{ lineTotal: 420 }], "collection", database), /not currently available/);
    const publicApi = load("app/api/checkout/discount/route.ts");
    const quoteRequest = (code: string, items = [{ sku: "AMINA-LAV-OS", quantity: 1 }], origin?: string) => new Request("https://test.invalid/api/checkout/discount", { method: "POST", headers: { "Content-Type": "application/json", ...(origin ? { origin } : {}) }, body: JSON.stringify({ code, items, fulfilmentMethod: "delivery", total: 1 }) });
    const before = (await postgres.query("select id from orders")).rows.length;
    const quoteResponse = await publicApi.POST(quoteRequest("new15"));
    assert.equal(quoteResponse.status, 200); assert.equal((await quoteResponse.json()).quote.total, 456);
    assert.equal((await postgres.query("select id from orders")).rows.length, before, "preview never creates an order");
    assert.equal((await publicApi.POST(quoteRequest("NEW15", [{ sku: "AMINA-LAV-OS", quantity: 6 }, { sku: "amina-lav-os", quantity: 6 }]))).status, 400);
    assert.equal((await publicApi.POST(quoteRequest("NEW15", undefined, "https://hostile.invalid"))).status, 403);
    const adminRequest = (origin?: string) => new Request("https://test.invalid/api/admin/discounts", { method: "POST", headers: { "Content-Type": "application/json", ...(origin ? { origin } : {}) }, body: JSON.stringify(create({ code: "ADMIN20", active: true })) });
    admin = null; assert.equal((await api.GET(new Request("https://test.invalid/api/admin/discounts"))).status, 401);
    assert.equal((await api.POST(adminRequest())).status, 401);
    admin = { email: "packer@example.test", role: "fulfilment" }; assert.equal((await api.POST(adminRequest())).status, 401);
    admin = { email: "manager@example.test", role: "manager" };
    assert.equal((await api.POST(adminRequest("https://hostile.invalid"))).status, 403);
    assert.equal((await api.POST(adminRequest())).status, 200);
    env.DISCOUNTS_ENABLED = "false";
    assert.equal((await api.GET(new Request("https://test.invalid/api/admin/discounts"))).status, 503);
    await assert.rejects(checkoutPricing("NEW15", [{ lineTotal: 420 }], "collection", database), /Discount codes are not currently available/);
    const history = (await postgres.query("select * from discount_history")).rows;
    assert.ok(history.length >= 7); assert.equal(sent.length, 2, "no email is triggered by a discount edit");
  } finally { globalThis.fetch = originalFetch; await postgres.close(); }
});
